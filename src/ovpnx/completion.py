"""TAB completion for bash and zsh.

The shell scripts are tiny: they hand the words typed so far to
'ovpnx _complete', and this module decides what to suggest. That keeps all the
logic in Python where it is tested. Suggestions for profile names are read
from the config at the moment you press TAB, so they are always current.
"""
import os
import shlex
import sys
from pathlib import Path

from . import shortcuts

FILES = ":files"       # first output line meaning "complete file names"
GLOBAL_OPTS = ["--config", "-v", "--verbose", "--version", "-h", "--help"]
POSITIONALS = {"connect": ["platform", "profile"], "list": ["platform"]}
VALUE_FLAGS = {"--ports", "--dir", "--shell"}
BEGIN = "# >>> ovpnx completion >>>"
END = "# <<< ovpnx completion <<<"
SHELLS = ("bash", "zsh")


# ------------------------------------------------------------ the completer
def subcommands(parser):
    for action in parser._actions:
        choices = getattr(action, "choices", None)
        if choices and hasattr(action, "_name_parser_map"):
            return {name: sub for name, sub in choices.items() if not name.startswith("_")}
    return {}


def _flags(sub):
    return [opt for a in sub._actions for opt in a.option_strings
            if opt.startswith("--") or opt == "-h"]


def narrow(candidates, cur):
    """Prefix matches: exact case first, else ignoring case.

    Shells can only insert a suggestion that starts with what was typed, so
    substring matching (which 'ovpnx connect' itself accepts) is not offered here.
    """
    seen, unique = set(), []
    for c in candidates:
        if c not in seen:
            seen.add(c)
            unique.append(c)
    exact = [c for c in unique if c.startswith(cur)]
    if exact:
        return exact[:200]
    low = cur.lower()
    return [c for c in unique if c.lower().startswith(low)][:200]


def complete(words, parser, load_settings, list_profiles):
    """Suggestions for the line typed so far.

    words: the arguments after the program name; the last one is the word being
    completed (it may be empty). Returns a list of strings, or [FILES].
    """
    if not words:
        words = [""]
    cur, done = words[-1], list(words[:-1])

    config, i = None, 0
    while i < len(done):
        w = done[i]
        if w == "--config":
            if i + 1 >= len(done):
                return [FILES]
            config = done[i + 1]
            i += 2
        elif w.startswith("--config="):
            config = w.split("=", 1)[1]
            i += 1
        elif w in ("-v", "--verbose"):
            i += 1
        else:
            break
    rest = done[i:]
    subs = subcommands(parser)

    if not rest:
        if cur.startswith("-"):
            return narrow(GLOBAL_OPTS, cur)
        return narrow(sorted(subs), cur)
    name = rest[0]
    if name not in subs:
        return []

    positionals, pending = [], None
    for a in rest[1:]:
        if pending:
            pending = None
        elif a.startswith("-"):
            pending = a if a in VALUE_FLAGS else None
        else:
            positionals.append(a)
    if pending:
        return [FILES] if pending == "--dir" else (
            narrow(list(SHELLS), cur) if pending == "--shell" else [])

    if cur.startswith("-"):
        return narrow(_flags(subs[name]) + ["-h"], cur)

    kinds = POSITIONALS.get(name, [])
    if len(positionals) >= len(kinds):
        return []
    kind = kinds[len(positionals)]
    settings = load_settings(config)
    if settings is None:
        return []
    if kind == "platform":
        return narrow(sorted(settings.platforms), cur)
    plat = settings.platforms.get(positionals[0].lower())
    if plat is None:
        return []
    return narrow(list_profiles(plat), cur)


# ------------------------------------------------------------ shell scripts
def _runner(python, parent):
    python = python or sys.executable or "python3"
    parent = parent or shortcuts._package_parent()
    env = ""
    if shortcuts._needs_pythonpath(parent):
        env = "PYTHONPATH=%s${PYTHONPATH:+:$PYTHONPATH} " % shlex.quote(parent)
    return "__ovpnx_run() { %s%s -m ovpnx \"$@\"; }" % (env, shlex.quote(python))


_BASH = r'''# ovpnx TAB completion for bash (generated by 'ovpnx install-completion')
%(runner)s
_ovpnx_complete() {
  local cur="${COMP_WORDS[COMP_CWORD]}" prog="${COMP_WORDS[0]##*/}" out line
  COMPREPLY=()
  out=$(__ovpnx_run _complete -- "$prog" "${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null) || return 0
  if [[ "${out%%%%$'\n'*}" == "%(files)s" ]]; then
    COMPREPLY=($(compgen -f -- "$cur"))
    return 0
  fi
  while IFS= read -r line; do
    [[ -n "$line" ]] && COMPREPLY+=("$(printf '%%q' "$line")")
  done <<< "$out"
}
complete -F _ovpnx_complete %(names)s
'''

_ZSH = r'''# ovpnx TAB completion for zsh (generated by 'ovpnx install-completion')
%(runner)s
_ovpnx_complete() {
  local -a out
  out=("${(@f)$(__ovpnx_run _complete -- "${words[1]:t}" "${(@)words[2,CURRENT]}" 2>/dev/null)}")
  if [[ "${out[1]}" == "%(files)s" ]]; then
    _files
    return
  fi
  out=("${(@)out:#}")
  (( ${#out} )) && compadd -U -V ovpnx -- "${out[@]}"
}
(( $+functions[compdef] )) || { autoload -Uz compinit && compinit -u; }
compdef _ovpnx_complete %(names)s
'''


def script_text(shell, names, python=None, parent=None):
    template = {"bash": _BASH, "zsh": _ZSH}[shell]
    return template % {"runner": _runner(python, parent), "files": FILES,
                       "names": " ".join(shlex.quote(n) for n in names)}


# ------------------------------------------------------ files and rc editing
def detect_shell(environ=None):
    env = os.environ if environ is None else environ
    name = os.path.basename(env.get("SHELL", ""))
    return name if name in SHELLS else None


def data_dir(environ=None):
    env = os.environ if environ is None else environ
    base = env.get("XDG_DATA_HOME")
    if base and os.path.isabs(base):
        return Path(base) / "ovpnx"
    home = env.get("HOME") or str(Path.home())
    return Path(home) / ".local" / "share" / "ovpnx"


def script_path(shell, environ=None):
    return data_dir(environ) / ("completion.%s" % shell)


def rc_path(shell, environ=None):
    env = os.environ if environ is None else environ
    home = env.get("HOME") or str(Path.home())
    if shell == "zsh":
        return Path(env.get("ZDOTDIR") or home) / ".zshrc"
    return Path(home) / ".bashrc"


def names_for(platforms):
    return ["ovpnx"] + shortcuts.names_for(platforms)


def write_script(shell, names, environ=None, python=None, parent=None):
    path = script_path(shell, environ)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(script_text(shell, names, python, parent))
    return path


def _strip_block(text):
    if BEGIN not in text:
        return text, False
    start = text.index(BEGIN)
    stop = text.find(END, start)
    if stop == -1:
        return text, False
    after = stop + len(END)
    if text[after:after + 1] == "\n":
        after += 1
    before = text[:start].rstrip("\n")
    return (before + "\n" if before else "") + text[after:].lstrip("\n"), True


def rc_has_block(rc):
    try:
        return BEGIN in Path(rc).read_text()
    except OSError:
        return False


def rc_add(rc, script):
    rc = Path(rc)
    try:
        text = rc.read_text()
    except OSError:
        text = ""
    text, _ = _strip_block(text)
    block = '%s\n[ -f %s ] && . %s\n%s\n' % (BEGIN, shlex.quote(str(script)),
                                             shlex.quote(str(script)), END)
    rc.parent.mkdir(parents=True, exist_ok=True)
    rc.write_text((text.rstrip("\n") + "\n\n" if text.strip() else "") + block)


def rc_remove(rc):
    rc = Path(rc)
    try:
        text = rc.read_text()
    except OSError:
        return False
    new, changed = _strip_block(text)
    if changed:
        rc.write_text(new)
    return changed
